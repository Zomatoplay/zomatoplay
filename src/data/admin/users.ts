interface UserSeed {
  id: string;
  displayId: string;
  fullName: string;
  email: string;
  phone: string;
  registeredAt: string;
  lastActiveAt: string;
  status?: AdminUserStatus;
  kycStatus?: KycStatus;
  vipLevel?: VipLevelId;
  referralCode: string;
  referredByCode?: string | null;
  referralCount?: number;
  walletAddress: string;
  totals?: Partial<AdminUserTotals>;
  restrictions?: Partial<AdminUserRestrictions>;
  twoFactorEnabled?: boolean;
  country?: string;
  internalNote?: string;
}

const NO_RESTRICTIONS: AdminUserRestrictions = {
  accountFrozen: false,
  withdrawalsFrozen: false,
  investmentsFrozen: false,
};

const NO_TOTALS: AdminUserTotals = {
  availableUsdt: 0,
  lockedUsdt: 0,
  totalDeposited: 0,
  totalInvested: 0,
  totalProfit: 0,
  totalWithdrawn: 0,
};

function user(seed: UserSeed): AdminUser {
  return {
    id: seed.id,
    displayId: seed.displayId,
    fullName: seed.fullName,
    email: seed.email,
    phone: seed.phone,
    country: seed.country ?? "India",
    registeredAt: seed.registeredAt,
    lastActiveAt: seed.lastActiveAt,
    status: seed.status ?? "active",
    kycStatus: seed.kycStatus ?? "verified",
    vipLevel: seed.vipLevel ?? "vip1",
    referralCode: seed.referralCode,
    referredByCode: seed.referredByCode ?? null,
    referralCount: seed.referralCount ?? 0,
    walletAddress: seed.walletAddress,
    totals: { ...NO_TOTALS, ...seed.totals },
    restrictions: { ...NO_RESTRICTIONS, ...seed.restrictions },
    twoFactorEnabled: seed.twoFactorEnabled ?? false,
    internalNote: seed.internalNote,
  };
}

