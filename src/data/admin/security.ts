export function getSessionsForUser(userId: string): UserDeviceSession[] {
  return userDeviceSessions.filter((s) => s.userId === userId);
}

export function getSecurityEventsForUser(userId: string): UserSecurityEvent[] {
  return userSecurityEvents.filter((e) => e.userId === userId);
}

